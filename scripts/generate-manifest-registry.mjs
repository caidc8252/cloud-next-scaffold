// Generates each app's manifest/_generated/apps.ts — a SELF-CONTAINED data file
// holding every app's serialized manifest + the aggregated contract keys.
//
// Why serialize instead of importing each app's _menu.map by reference: in a
// multi-Next-app monorepo, one app importing another app's source files is a
// bundling hazard. Serializing the data inline leaves only an erasable
// `import type`, so every app bundles cleanly with no cross-app source imports.
//
// Convention: every apps/<app>/manifest/_menu.map.ts MUST export `appManifest`.
// Run via `pnpm gen:manifest` (also wired into predev / prebuild / pretest).
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const appsDir = join(root, "apps");

function menuMapFile(appDir) {
  for (const ext of ["ts", "tsx"]) {
    const file = join(appsDir, appDir, "manifest", `_menu.map.${ext}`);
    if (existsSync(file)) return file;
  }
  return null;
}

// 死写角色文件（可选）：apps/<app>/manifest/_roles.map.ts 导出 `appRoles`。
function roleMapFile(appDir) {
  for (const ext of ["ts", "tsx"]) {
    const file = join(appsDir, appDir, "manifest", `_roles.map.${ext}`);
    if (existsSync(file)) return file;
  }
  return null;
}

const appDirectories = readdirSync(appsDir)
  .filter((name) => statSync(join(appsDir, name)).isDirectory())
  .sort((a, b) => a.localeCompare(b));

const sourceApps = appDirectories
  .map((name) => ({ name, file: menuMapFile(name) }))
  .filter((app) => app.file !== null)
  .sort((a, b) => a.name.localeCompare(b.name));

if (sourceApps.length === 0) {
  throw new Error("[gen:manifest] no apps/*/manifest/_menu.map.ts found");
}

// 评估每个 _menu.map，取出 appManifest 数据（Node 24 原生 TS 类型擦除，无需额外 loader）。
const manifests = [];
for (const app of sourceApps) {
  const mod = await import(pathToFileURL(app.file).href);
  const manifest = mod.appManifest;
  if (!manifest ) {
    throw new Error(`[gen:manifest] apps/${app.name}/manifest/_menu.map: missing export \`appManifest\``);
  }
  manifests.push(manifest);
}


// 死写角色：各 app 可选的 _roles.map.ts 导出 `appRoles`（RoleDef[]）。拍平成全局池。
// roleId 区间 / 唯一性 / 权限码存在性由 createPlatformConfig 在构造期校验。
const roles = [];
for (const app of sourceApps) {
  const file = roleMapFile(app.name);
  if (!file) continue;
  const mod = await import(pathToFileURL(file).href);
  if (!mod.appRoles) {
    throw new Error(`[gen:manifest] apps/${app.name}/manifest/_roles.map: missing export \`appRoles\``);
  }
  roles.push(...mod.appRoles);
}

// 全局契约枚举 = 各 app 声明的 contractKeys 并集（替代旧 _contracts.ts）。
const contractKeys = [...new Set(manifests.flatMap((m) => m.contractKeys ?? []))].sort();

// 全局菜单池 = 各 app 菜单拍平成一份。
// menuCode / permissionCode 全局唯一，由 createPlatformConfig 在构造期校验。
const menus = manifests.flatMap((m) => m.menus ?? []);

// COC 文案：各 app co-located 的 manifest/i18n/{locale}.json，按 locale 取并集。
// 文案随菜单/角色走同一条管线 → 全量并集，每个 key 在归属 app 写一次（单一真源）。
const LOCALES = ["en", "zh-CN", "ja"];

function i18nFile(appName, locale) {
  const f = join(appsDir, appName, "manifest", "i18n", `${locale}.json`);
  return existsSync(f) ? f : null;
}

// 深合并（coc 三段 menu/permission/role，全局 key 唯一，正常不撞）。
function mergeInto(target, src) {
  for (const k of Object.keys(src)) {
    if (src[k] && typeof src[k] === "object" && !Array.isArray(src[k])) {
      target[k] = mergeInto(target[k] ?? {}, src[k]);
    } else {
      target[k] = src[k];
    }
  }
  return target;
}

const cocByLocale = Object.fromEntries(LOCALES.map((l) => [l, {}]));
for (const app of sourceApps) {
  for (const locale of LOCALES) {
    const f = i18nFile(app.name, locale);
    if (!f) continue;
    mergeInto(cocByLocale[locale], JSON.parse(readFileSync(f, "utf8")));
  }
}

const content = `// AUTO-GENERATED by scripts/generate-manifest-registry.mjs — do not edit.
// Run \`pnpm gen:manifest\` (also wired into predev / prebuild / pretest).
// Self-contained: every app's menus are serialized inline into one flat pool; the
// only import is an erasable type import, so there are no cross-app source imports.
import type { MenuEntry, RoleDef } from "@cloud/platform-config";

export const MENUS: MenuEntry[] = ${JSON.stringify(menus, null, 2)};

export const CONTRACT_KEYS: string[] = ${JSON.stringify(contractKeys)};

export const ROLES: RoleDef[] = ${JSON.stringify(roles, null, 2)};
`;

// 每个含 manifest/ 消费目录的 app 各写一份全量 barrel。
// site 这类消费者无需提供 _menu.map，也不会向全局池贡献菜单或契约。
const targetApps = appDirectories.filter((name) =>
  existsSync(join(appsDir, name, "manifest")),
);
for (const appName of targetApps) {
  const generatedDir = join(appsDir, appName, "manifest", "_generated");
  mkdirSync(generatedDir, { recursive: true });
  writeFileSync(join(generatedDir, "apps.ts"), content, "utf8");

  // coc 文案产物（全量并集，按 locale 拆文件，request.ts 挂到 coc 命名空间）。
  const i18nDir = join(generatedDir, "i18n");
  mkdirSync(i18nDir, { recursive: true });
  for (const locale of LOCALES) {
    writeFileSync(join(i18nDir, `${locale}.json`), JSON.stringify(cocByLocale[locale], null, 2) + "\n", "utf8");
  }
}

console.log(
  `[gen:manifest] collected ${sourceApps.length} provider(s): ` +
    `${sourceApps.map((app) => app.name).join(", ")}; wrote ${targetApps.length} consumer(s): ` +
    `${targetApps.join(", ")} ` +
    `(contracts: ${contractKeys.join(", ")}; roles: ${roles.length})`,
);

// 预置超管完整性检查（非阻断）：缺码只警告，绝不让 gen 失败。
try {
  await import(pathToFileURL(join(root, "scripts", "check-preset-admin-coverage.mjs")).href);
} catch (err) {
  console.warn(`[gen:manifest] coverage check skipped: ${err?.message ?? err}`);
}
