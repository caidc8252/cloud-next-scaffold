// Generates apps/web/manifest/_generated/apps.ts — a barrel that imports every
// app's platform manifest so instrumentation can register them all at startup.
//
// Convention: every apps/<app>/manifest/index.ts MUST export `appManifest`.
// Run via `pnpm gen:manifest` (also wired into predev / prebuild).
import { mkdirSync, readdirSync, writeFileSync, existsSync, statSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const appsDir = join(root, "apps");
const generatedDir = join(root, "apps", "web", "manifest", "_generated");
const outFile = join(generatedDir, "apps.ts");

function manifestEntry(appDir) {
  for (const ext of ["ts", "tsx"]) {
    const file = join(appsDir, appDir, "manifest", `index.${ext}`);
    if (existsSync(file)) return join(appsDir, appDir, "manifest", "index");
  }
  return null;
}

function toIdentifier(name) {
  const id = name.replace(/[^a-zA-Z0-9_$]/g, "_");
  return /^[0-9]/.test(id) ? `_${id}` : id;
}

function toImportPath(targetNoExt) {
  let rel = relative(generatedDir, targetNoExt).split("\\").join("/");
  if (!rel.startsWith(".")) rel = `./${rel}`;
  return rel;
}

const apps = readdirSync(appsDir)
  .filter((name) => statSync(join(appsDir, name)).isDirectory())
  .map((name) => ({ name, target: manifestEntry(name) }))
  .filter((app) => app.target !== null)
  .sort((a, b) => a.name.localeCompare(b.name));

if (apps.length === 0) {
  throw new Error("[gen:manifest] no apps/*/manifest/index.ts found");
}

const imports = apps
  .map((app) => `import { appManifest as ${toIdentifier(app.name)} } from "${toImportPath(app.target)}";`)
  .join("\n");
const list = apps.map((app) => toIdentifier(app.name)).join(", ");

const content = `// AUTO-GENERATED by scripts/generate-manifest-registry.mjs — do not edit.
// Run \`pnpm gen:manifest\` (also wired into predev / prebuild).
${imports}

export const APP_MANIFESTS = [${list}];
`;

mkdirSync(generatedDir, { recursive: true });
writeFileSync(outFile, content, "utf8");
console.log(`[gen:manifest] wrote ${relative(root, outFile)} (${apps.length} app(s): ${apps.map((a) => a.name).join(", ")})`);
